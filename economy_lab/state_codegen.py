"""Generate the C# state model from the laboratory's own classes (docs/141 §4).

The port's state classes and their JSON reader and writer are a mechanical
transcription of ``model.py``'s dataclasses and of ``state_codec``'s
layout, so they are generated rather than typed: 190 fields copied by hand
is 190 chances to misspell one.  Run it when the model's fields change and
commit what it writes:

    python -m economy_lab.state_codegen

Writes ``Economy.Core/Model/State.g.cs`` and
``Economy.Core.Check/StateJson.g.cs`` under ``rimworld/economy_mod/Source``.
The reader is strict: an object with a field it does not expect, or
missing one it does, throws with the path.  ``Region.reserves``,
``Region.projects`` and the day's extraction table must be empty, because
the docked configuration carries none (docs/141 §2).
"""
from __future__ import annotations

import dataclasses
import inspect
import math
from pathlib import Path

from . import model
from .state_codec import encode
from .wright_battery import DOCKED, build_ours

ROOT = Path(__file__).resolve().parents[1] / "rimworld" / "economy_mod" / "Source"
CLASSES = (model.Commodity, model.Process, model.Producer, model.Region,
           model.Route, model.Shipment, model.Ledger)
#: Fields whose value must be empty in a docked economy; not carried.
EMPTY = {("Region", "reserves"): "{}", ("Region", "projects"): "[]"}
TUPLES = {
    "List[Tuple[int, str, str]]": ("Bankruptcy", (("Day", "int"), ("Region", "string"), ("Producer", "string"))),
    "List[Tuple[int, str, str, float]]": ("ExitRecord", (("Day", "int"), ("Region", "string"), ("Producer", "string"), ("Withdrawn", "double"))),
}
PRIMITIVE = {"float": "double", "int": "int", "bool": "bool", "str": "string"}


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.strip("_").split("_"))


def kind(annotation: str) -> tuple:
    """(C# type, how to read, how to write) for a field annotation."""
    if annotation in PRIMITIVE:
        return ("prim", PRIMITIVE[annotation])
    if annotation == "Dict[str, float]":
        return ("nummap", "OrderedMap<double>")
    if annotation == "Optional[Process]":
        return ("process", "Process")
    if annotation == "List[Producer]":
        return ("producers", "List<Producer>")
    if annotation in TUPLES:
        name = TUPLES[annotation][0]
        return ("tuples", f"List<{name}>", name)
    raise TypeError(f"no C# mapping for {annotation!r}")


def fields(cls):
    for field in dataclasses.fields(cls):
        yield field.name, field.type


def literal(ctype: str, value) -> str:
    """A C# literal for a Python default, exact: ``repr`` round-trips and
    Roslyn parses decimal literals correctly rounded."""
    if ctype == "double":
        value = float(value)
        if math.isinf(value):
            return "double.PositiveInfinity" if value > 0 else "double.NegativeInfinity"
        return repr(value)
    if ctype == "int":
        return str(int(value))
    if ctype == "bool":
        return "true" if value else "false"
    if ctype == "string":
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    raise TypeError(ctype)


def defaults(cls):
    """Scalar defaults a dataclass declares, by field name."""
    return {field.name: field.default for field in dataclasses.fields(cls)
            if field.default is not dataclasses.MISSING
            and isinstance(field.default, (bool, int, float, str))}


READ_PRIM = {"double": "Num({e})", "int": "Int({e})", "bool": "{e}.GetBoolean()", "string": "Str({e})"}
WRITE_PRIM = {"double": "w.WriteNumber(\"{n}\", {v});", "int": "w.WriteNumber(\"{n}\", {v});",
              "bool": "w.WriteBoolean(\"{n}\", {v});", "string": "w.WriteString(\"{n}\", {v});"}


def generate():
    sample = build_ours(0, commodities=8, regions=2, **DOCKED)
    scalars = encode(sample)["economy"]

    state = ["// <auto-generated> by economy_lab/state_codegen.py from economy_lab/model.py.",
             "// Do not edit; regenerate. </auto-generated>",
             "using System.Collections.Generic;", "",
             "namespace SocialProduction.Economy.Core.Model", "{"]
    reader = ["// <auto-generated> by economy_lab/state_codegen.py. Do not edit; regenerate. </auto-generated>",
              "using System.Collections.Generic;", "using System.Text.Json;",
              "using SocialProduction.Economy.Core.Model;", "",
              "namespace SocialProduction.Economy.Check", "{",
              "    public static partial class StateJson", "    {"]

    for tuple_name, members in TUPLES.values():
        state.append(f"    /// <summary>A tuple in the laboratory's ledger.</summary>")
        state.append(f"    public sealed class {tuple_name}")
        state.append("    {")
        for member, ctype in members:
            state.append(f"        public {ctype} {member};")
        state.append("    }")
        state.append("")
        reader.append(f"        private static {tuple_name} Read{tuple_name}(JsonElement e, string path)")
        reader.append("        {")
        reader.append(f"            ExpectArray(e, path, {len(members)});")
        reader.append(f"            {tuple_name} t = new {tuple_name}();")
        for position, (member, ctype) in enumerate(members):
            reader.append(f"            t.{member} = " + READ_PRIM[ctype].format(e=f"e[{position}]") + ";")
        reader.append("            return t;")
        reader.append("        }")
        reader.append("")
        reader.append(f"        private static void Write{tuple_name}(Utf8JsonWriter w, {tuple_name} t)")
        reader.append("        {")
        reader.append("            w.WriteStartArray();")
        for member, ctype in members:
            call = {"double": "w.WriteNumberValue(t.{m});", "int": "w.WriteNumberValue(t.{m});",
                    "string": "w.WriteStringValue(t.{m});"}[ctype]
            reader.append("            " + call.format(m=member))
        reader.append("            w.WriteEndArray();")
        reader.append("        }")
        reader.append("")

    for cls in CLASSES:
        name = cls.__name__
        state.append(f"    /// <summary>The laboratory's <c>{name}</c>, field for field.</summary>")
        state.append(f"    public sealed class {name}")
        state.append("    {")
        names = []
        read = [f"        private static {name} Read{name}(JsonElement e, string path, OrderedMap<Process> processes)",
                "        {", f"            {name} x = new {name}();"]
        write = [f"        private static void Write{name}(Utf8JsonWriter w, {name} x)", "        {",
                 "            w.WriteStartObject();"]
        for field, annotation in fields(cls):
            names.append(field)
            member = pascal(field)
            el = f"e.GetProperty(\"{field}\")"
            sub = f"path + \".{field}\""
            if (name, field) in EMPTY:
                read.append(f"            ExpectEmpty({el}, {sub});")
                write.append(f"            w.WritePropertyName(\"{field}\");")
                write.append("            w.WriteStart" + ("Object" if EMPTY[(name, field)] == "{}" else "Array") + "();")
                write.append("            w.WriteEnd" + ("Object" if EMPTY[(name, field)] == "{}" else "Array") + "();")
                continue
            k = kind(annotation)
            if k[0] == "prim":
                initial = defaults(cls).get(field)
                suffix = "" if initial is None else " = " + literal(k[1], initial)
                state.append(f"        public {k[1]} {member}{suffix};")
                read.append(f"            x.{member} = " + READ_PRIM[k[1]].format(e=el) + ";")
                write.append("            " + WRITE_PRIM[k[1]].format(n=field, v=f"x.{member}"))
            elif k[0] == "nummap":
                state.append(f"        public OrderedMap<double> {member} = new OrderedMap<double>();")
                read.append(f"            x.{member} = NumMap({el}, {sub});")
                write.append(f"            WriteNumMap(w, \"{field}\", x.{member});")
            elif k[0] == "process":
                state.append(f"        public Process {member};")
                read.append(f"            x.{member} = ProcessRef({el}, {sub}, processes);")
                write.append(f"            if (x.{member} == null) {{ w.WriteNull(\"{field}\"); }} else {{ w.WriteString(\"{field}\", x.{member}.Name); }}")
            elif k[0] == "producers":
                state.append(f"        public List<Producer> {member} = new List<Producer>();")
                read.append(f"            foreach (JsonElement item in {el}.EnumerateArray()) {{ x.{member}.Add(ReadProducer(item, {sub}, processes)); }}")
                write.append(f"            w.WriteStartArray(\"{field}\");")
                write.append(f"            foreach (Producer item in x.{member}) {{ WriteProducer(w, item); }}")
                write.append("            w.WriteEndArray();")
            elif k[0] == "tuples":
                tuple_name = k[2]
                state.append(f"        public List<{tuple_name}> {member} = new List<{tuple_name}>();")
                read.append(f"            foreach (JsonElement item in {el}.EnumerateArray()) {{ x.{member}.Add(Read{tuple_name}(item, {sub})); }}")
                write.append(f"            w.WriteStartArray(\"{field}\");")
                write.append(f"            foreach ({tuple_name} item in x.{member}) {{ Write{tuple_name}(w, item); }}")
                write.append("            w.WriteEndArray();")
        state.append("    }")
        state.append("")
        read.insert(2, "            ExpectFields(e, path, " + name + "Fields);")
        read.append("            return x;")
        read.append("        }")
        write.append("            w.WriteEndObject();")
        write.append("        }")
        reader.append(f"        private static readonly string[] {name}Fields = {{ " +
                      ", ".join(f'"{n}"' for n in names) + " };")
        reader.extend(read)
        reader.append("")
        reader.extend(write)
        reader.append("")

    # The economy's own scalars, in attribute order.
    state.append("    /// <summary>The laboratory's <c>Economy</c>: its settings and counters,")
    state.append("    /// then the sections <c>state_codec</c> lays out.</summary>")
    state.append("    public sealed partial class EconomyState")
    state.append("    {")
    read = ["        private static void ReadScalars(JsonElement e, EconomyState x)", "        {",
            "            ExpectFields(e, \"economy\", ScalarFields);"]
    write = ["        private static void WriteScalars(Utf8JsonWriter w, EconomyState x)", "        {",
             "            w.WriteStartObject(\"economy\");"]
    parameters = inspect.signature(model.Economy.__init__).parameters
    constructor = []
    for field, value in scalars.items():
        ctype = {bool: "bool", int: "int", float: "double", str: "string"}[type(value)]
        member = pascal(field)
        state.append(f"        public {ctype} {member};")
        parameter = parameters.get(field)
        if parameter is not None and parameter.default is not inspect.Parameter.empty:
            constructor.append(f"            {member} = {literal(ctype, parameter.default)};")
        read.append(f"            x.{member} = " + READ_PRIM[ctype].format(e=f"e.GetProperty(\"{field}\")") + ";")
        write.append("            " + WRITE_PRIM[ctype].format(n=field, v=f"x.{member}"))
    state.append("")
    state.append("        /// <summary>Every setting <c>Economy.__init__</c> takes, at its default.</summary>")
    state.append("        public void ApplyConstructorDefaults()")
    state.append("        {")
    state.extend(constructor)
    state.append("        }")
    state.append("    }")
    state.append("}")
    read.append("        }")
    write.append("            w.WriteEndObject();")
    write.append("        }")
    reader.append("        private static readonly string[] ScalarFields = { " +
                  ", ".join(f'"{n}"' for n in scalars) + " };")
    reader.extend(read)
    reader.append("")
    reader.extend(write)
    reader.append("    }")
    reader.append("}")

    (ROOT / "Economy.Core" / "Model" / "State.g.cs").write_text("\n".join(state) + "\n", encoding="utf-8")
    (ROOT / "Economy.Core.Check" / "StateJson.g.cs").write_text("\n".join(reader) + "\n", encoding="utf-8")
    print(f"{sum(1 for c in CLASSES for _ in fields(c))} fields in {len(CLASSES)} classes, "
          f"{len(scalars)} economy scalars")


if __name__ == "__main__":
    generate()
