"""Generate the C# port's copy of the commodity population (docs/141 slice 2).

    python3.12 -m economy_lab.population_codegen

Writes ``Economy.Core/Model/Population.g.cs``: the rows ``scale.population()``
returns -- priced rows only, sorted by name -- with every float carried as
its IEEE-754 bit pattern.  A decimal literal would make the port's numbers
depend on the parser that reads it, and Mono's is not promised to round
correctly; a bit pattern cannot be misread.
"""
from __future__ import annotations

import struct
from pathlib import Path

from .scale import population

TARGET = (Path(__file__).resolve().parents[1] / "rimworld" / "economy_mod" / "Source"
          / "Economy.Core" / "Model" / "Population.g.cs")


def bits(value: float) -> str:
    return "0x%016XUL" % struct.unpack("<Q", struct.pack("<d", value))[0]


def generate() -> int:
    rows = population()
    lines = [
        "// <auto-generated> by economy_lab/population_codegen.py from",
        "// economy_lab/data/embodied_labor.csv. Do not edit; regenerate. </auto-generated>",
        "namespace SocialProduction.Economy.Core.Model",
        "{",
        "    public static partial class Population",
        "    {",
        "        /// <summary><c>scale.population()</c>: priced rows sorted by name;",
        "        /// labor and price as bit patterns.</summary>",
        "        private static readonly Row[] All =",
        "        {",
    ]
    for row in rows:
        if any(ch in row["name"] for ch in '"\\'):
            raise ValueError(f"name needs escaping: {row['name']!r}")
        lines.append(f'            new Row("{row["name"]}", {row["depth"]}, '
                     f'{bits(row["labor"])}, {bits(row["price"])}),')
    lines += ["        };", "    }", "}", ""]
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    return len(rows)


if __name__ == "__main__":
    print(f"{generate()} rows")
